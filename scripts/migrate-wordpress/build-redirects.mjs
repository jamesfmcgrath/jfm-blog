import { readFile, writeFile } from 'node:fs/promises';
import xml2js from 'xml2js';

export async function buildRedirects(xmlString) {
	const parsed = await xml2js.parseStringPromise(xmlString);
	const items = parsed.rss.channel[0].item ?? [];

	// Collect all post and page (post_id 1039) permalinks to avoid collisions
	const postPermalinks = new Set();
	items.forEach((item) => {
		const postType = item['wp:post_type']?.[0];
		const postId = item['wp:post_id']?.[0];
		const link = item.link?.[0];

		// Include posts and the one kept page (post_id 1039)
		if ((postType === 'post' || (postType === 'page' && postId === '1039')) && link) {
			try {
				const path = decodeURIComponent(new URL(link).pathname);
				postPermalinks.add(path);
			} catch {
				// Skip items with invalid links
			}
		}
	});

	const lines = items
		.filter((item) => {
			const postType = item['wp:post_type']?.[0];
			const link = item.link?.[0];

			// Skip if not an attachment
			if (postType !== 'attachment') return false;

			// Skip if missing link (defensive handling)
			if (!link) return false;

			try {
				const path = decodeURIComponent(new URL(link).pathname);
				// Skip if this attachment's link collides with a post/page permalink
				if (postPermalinks.has(path)) return false;

				return true;
			} catch {
				// Skip items with invalid links
				return false;
			}
		})
		.map((item) => {
			const link = item.link?.[0];
			// Apache matches RedirectMatch against the decoded URL path, so percent-encoded
			// non-ASCII characters in the WordPress permalink would never match.
			const path = decodeURIComponent(new URL(link).pathname);
			return `RedirectMatch 301 ^${path}$ /`;
		});

	return [
		'# Generated by scripts/migrate-wordpress/build-redirects.mjs',
		'# Old WordPress attachment permalinks, which have no equivalent page on the new site.',
		...lines,
		'',
	].join('\n');
}

async function main() {
	const [, , inputPath, outputPath] = process.argv;
	if (!inputPath || !outputPath) {
		console.error('Usage: node build-redirects.mjs <input.xml> <output .htaccess>');
		process.exit(1);
	}

	const xml = await readFile(inputPath, 'utf8');
	const redirects = await buildRedirects(xml);
	await writeFile(outputPath, redirects, 'utf8');
	console.log(`Wrote ${outputPath}`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
	await main();
}
